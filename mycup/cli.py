#!/usr/bin/env python3
"""my_cup 工具链入口。

用法：
    uv run mycup <command> [options]

命令：
    init     生成 verilator.f（lint 文件清单）
    lint     Verilator 静态检查
    test     运行 cocotb + pytest
    prog     用指定 hex 程序运行指令级测试
    clean    清理生成物
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
from datetime import datetime
from pathlib import Path
from typing import NoReturn

ROOT_FALLBACK = Path.cwd()


def _find_root(start: Path) -> Path:
    for candidate in (start, *start.parents):
        if (candidate / "pyproject.toml").is_file() and (candidate / "rtl").is_dir():
            return candidate
    return ROOT_FALLBACK


ROOT = _find_root(Path(__file__).resolve().parent)

RTL_DIR = ROOT / "rtl"
BUILD_DIR = ROOT / "build"
WAVES_DIR = ROOT / "waves"
LOGS_DIR = ROOT / "logs"

VERILATOR_F = ROOT / "verilator.f"
VERILATOR_FLAGS = ["--lint-only", "-Wall", "--timing", "--bbox-sys"]
LINT_LOG = LOGS_DIR / "lint.log"


# --------------------------------------------------------------------------- #
# helpers
# --------------------------------------------------------------------------- #
def now() -> str:
    return datetime.now().strftime("%Y-%m-%d %H:%M:%S")


def ensure_dirs() -> None:
    for directory in (BUILD_DIR, WAVES_DIR, LOGS_DIR):
        directory.mkdir(parents=True, exist_ok=True)


def rel(path: Path) -> str:
    return path.relative_to(ROOT).as_posix()


def log_line(path: Path, message: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as fh:
        fh.write(message + "\n")


def fail(message: str, code: int = 1) -> NoReturn:
    print(message, file=sys.stderr)
    raise SystemExit(code)


def rtl_files() -> list[Path]:
    """返回所有 RTL 源文件，并保证 cpu_pkg.sv 排在最前面。

    SystemVerilog 的 package 必须先于使用它的模块被编译，
    而 iverilog / verilator 不会自动解析依赖，所以这里手动排序。
    """
    files = sorted(p for p in RTL_DIR.rglob("*") if p.suffix in (".v", ".sv"))
    package = [p for p in files if p.name == "cpu_pkg.sv"]
    others = [p for p in files if p.name != "cpu_pkg.sv"]
    return package + others


def write_verilator_f() -> Path:
    """生成 Verilator lint 用的文件清单。"""
    lines = ["// Generated by mycup/cli.py -- do not edit by hand"]
    lines.extend(VERILATOR_FLAGS)
    lines.extend(rel(p) for p in rtl_files())
    VERILATOR_F.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return VERILATOR_F


# --------------------------------------------------------------------------- #
# commands
# --------------------------------------------------------------------------- #
def cmd_init(_: argparse.Namespace) -> None:
    """只生成 verilator.f；IDE 和 lint 都复用这份清单。"""
    write_verilator_f()
    print(f"Generated {rel(VERILATOR_F)}")


def cmd_lint(_: argparse.Namespace) -> None:
    """刷新 verilator.f，然后跑 Verilator 静态检查。"""
    ensure_dirs()
    write_verilator_f()
    log_line(LINT_LOG, f"Linting: {now()}")

    proc = subprocess.run(
        ["verilator", "-f", str(VERILATOR_F)], cwd=ROOT, capture_output=True, text=True
    )
    output = proc.stdout + proc.stderr
    sys.stdout.write(output)
    with LINT_LOG.open("a", encoding="utf-8") as fh:
        fh.write(output)

    if proc.returncode != 0:
        raise SystemExit(proc.returncode)


def cmd_test(args: argparse.Namespace) -> None:
    """运行 cocotb + pytest。"""
    extra = list(args.pytest_args)
    if extra and extra[0] == "--":
        extra = extra[1:]
    cmd = [sys.executable, "-m", "pytest", "-v", *extra]
    raise SystemExit(subprocess.run(cmd, cwd=ROOT).returncode)


def cmd_prog(args: argparse.Namespace) -> None:
    """用指定 hex 程序运行指令级测试（tests/test_instr.py::test_prog_demo）。

    通过环境变量把程序路径/周期数传给 pytest 包装层和 cocotb 测试：
      MYCUP_PROG         指令存储器 hex 的绝对路径
      MYCUP_DATA         数据存储器 hex 的绝对路径（可选）
      MYCUP_PROG_CYCLES  指令跑完后等待的周期数
    """
    program = Path(args.hex).resolve()
    if not program.is_file():
        fail(f"program not found: {program}")

    env = {**os.environ}
    env["MYCUP_PROG"] = str(program)
    env["MYCUP_PROG_CYCLES"] = str(args.cycles)

    if args.data:
        data = Path(args.data).resolve()
        if not data.is_file():
            fail(f"data file not found: {data}")
        env["MYCUP_DATA"] = str(data)

    cmd = [
        sys.executable,
        "-m",
        "pytest",
        "-v",
        "tests/test_instr.py::test_prog_demo",
    ]
    raise SystemExit(subprocess.run(cmd, cwd=ROOT, env=env).returncode)


def cmd_clean(_: argparse.Namespace) -> None:
    """清理所有生成物。"""
    for directory in (
        BUILD_DIR,
        WAVES_DIR,
        LOGS_DIR,
        ROOT / ".pytest_cache",
        ROOT / "tests" / "__pycache__",
    ):
        shutil.rmtree(directory, ignore_errors=True)
    print("Cleaned build/, waves/, logs/, .pytest_cache/")


# --------------------------------------------------------------------------- #
# cli
# --------------------------------------------------------------------------- #
def make_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="mycup",
        description="my_cup 工具链（lint / test / 程序装载）",
    )
    sub = parser.add_subparsers(dest="command", required=True)

    sub.add_parser("init", help="生成 verilator.f").set_defaults(func=cmd_init)
    sub.add_parser("lint", help="运行 Verilator lint").set_defaults(func=cmd_lint)

    p_test = sub.add_parser("test", help="运行 cocotb + pytest")
    p_test.add_argument("pytest_args", nargs=argparse.REMAINDER)
    p_test.set_defaults(func=cmd_test)

    p_prog = sub.add_parser("prog", help="用 hex 程序运行指令级测试")
    p_prog.add_argument("hex", help="指令存储器 hex 文件")
    p_prog.add_argument("--data", help="数据存储器 hex 文件（可选）")
    p_prog.add_argument(
        "--cycles", type=int, default=4, help="程序跑完后等待的周期数（默认 4）"
    )
    p_prog.set_defaults(func=cmd_prog)

    sub.add_parser("clean", help="清理 build/ waves/ logs/ 等").set_defaults(
        func=cmd_clean
    )

    return parser


def main(argv: list[str] | None = None) -> int:
    sys.stdout.reconfigure(line_buffering=True)
    sys.stderr.reconfigure(line_buffering=True)
    parser = make_parser()
    args = parser.parse_args(argv)
    args.func(args)
    return 0


if __name__ == "__main__":
    sys.exit(main())
