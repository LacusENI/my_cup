#!/usr/bin/env python3
"""my_cup 工具链入口（取代原 Makefile 与 chore/*.sh）。

用法：
    uv run mycup <command> [options]

命令：
    init                生成全部文件清单（build/filelists/*.f + verilator.f）
    list                列出所有 testbench
    build <name>        编译单个 testbench
    run <name>          编译并运行单个 testbench
    all                 编译并运行全部 testbench
    wave <name>         用 gtkwave 打开波形
    lint                运行 Verilator lint
    test                运行 cocotb + pytest
    clean               清理 build/ waves/ logs/
"""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
from datetime import datetime
from pathlib import Path
from typing import NoReturn

ROOT_FALLBACK = Path.cwd()


def _find_root(start: Path) -> Path:
    for candidate in (start, *start.parents):
        if (candidate / "pyproject.toml").is_file() and (candidate / "rtl").is_dir():
            return candidate
    return ROOT_FALLBACK


ROOT = _find_root(Path(__file__).resolve().parent)

RTL_DIR = ROOT / "rtl"
TB_DIR = ROOT / "sim" / "tb"
BUILD_DIR = ROOT / "build"
F_DIR = BUILD_DIR / "filelists"
TARGET_DIR = BUILD_DIR / "targets"
WAVES_DIR = ROOT / "waves"
LOGS_DIR = ROOT / "logs"

INC_PATH = ["lib", "rtl/core/include", "sim/tb/include"]

VERILATOR_F = ROOT / "verilator.f"
VERILATOR_FLAGS = ["--lint-only", "-Wall", "--timing", "--bbox-sys"]

BUILD_LOG = LOGS_DIR / "build.log"
LINT_LOG = LOGS_DIR / "lint.log"


# --------------------------------------------------------------------------- #
# helpers
# --------------------------------------------------------------------------- #
def now() -> str:
    return datetime.now().strftime("%Y-%m-%d %H:%M:%S")


def ensure_dirs() -> None:
    for d in (BUILD_DIR, F_DIR, TARGET_DIR, WAVES_DIR, LOGS_DIR):
        d.mkdir(parents=True, exist_ok=True)


def rel(path: Path) -> str:
    return path.relative_to(ROOT).as_posix()


def log_line(path: Path, message: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as fh:
        fh.write(message + "\n")


def rtl_files() -> list[Path]:
    return sorted(RTL_DIR.rglob("*.v"))


def discover_tbs() -> dict[str, Path]:
    return {tb.stem: tb for tb in sorted(TB_DIR.rglob("tb_*.v"))}


def write_filelist(tb: Path) -> Path:
    ensure_dirs()
    out = F_DIR / f"{tb.stem}.f"
    lines = ["// Generated by mycup/cli.py -- do not edit by hand"]
    lines.extend(rel(p) for p in rtl_files())
    lines.append(rel(tb))
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out


def write_verilator_f() -> Path:
    lines = ["// Generated by mycup/cli.py -- do not edit by hand"]
    lines.extend(VERILATOR_FLAGS)
    lines.extend(f"-I{p}" for p in INC_PATH)
    lines.extend(rel(p) for p in rtl_files())
    VERILATOR_F.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return VERILATOR_F


def fail(message: str, code: int = 1) -> NoReturn:
    print(message, file=sys.stderr)
    raise SystemExit(code)


def require_tb(name: str) -> Path:
    tbs = discover_tbs()
    if name not in tbs:
        available = ", ".join(sorted(tbs)) or "(none)"
        fail(f"unknown testbench: {name}\navailable: {available}")
    return tbs[name]


# --------------------------------------------------------------------------- #
# commands
# --------------------------------------------------------------------------- #
def cmd_init(_: argparse.Namespace) -> None:
    ensure_dirs()
    tbs = discover_tbs()
    for tb in tbs.values():
        write_filelist(tb)
    write_verilator_f()
    print(f"Generated {len(tbs)} testbench filelists and {rel(VERILATOR_F)}")


def cmd_list(_: argparse.Namespace) -> None:
    for name in sorted(discover_tbs()):
        print(name)


def build(name: str) -> Path:
    tb = require_tb(name)
    filelist = write_filelist(tb)
    target = TARGET_DIR / name
    ensure_dirs()

    cmd = ["iverilog", "-g2012", "-o", str(target), "-f", str(filelist)]
    for inc in INC_PATH:
        cmd.extend(["-I", inc])

    log_line(BUILD_LOG, f"Build({name}): {now()}")
    proc = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)
    with BUILD_LOG.open("a", encoding="utf-8") as fh:
        fh.write(proc.stdout)
        fh.write(proc.stderr)

    if proc.returncode != 0:
        log_line(BUILD_LOG, "FAILED")
        sys.stderr.write(proc.stdout)
        sys.stderr.write(proc.stderr)
        fail(f"Build({name}): FAILED")

    log_line(BUILD_LOG, "OK")
    print(f"Build({name}): OK")
    return target


def run(name: str, prog: str | None = None, data: str | None = None) -> None:
    target = build(name)
    cmd = ["vvp", str(target)]
    if prog:
        cmd.append(f"+instr={prog}")
    if data:
        cmd.append(f"+data={data}")

    print(f"Run({name}): {now()}")
    proc = subprocess.run(cmd, cwd=ROOT)
    if proc.returncode != 0:
        fail(f"Run({name}): FAILED", proc.returncode)


def cmd_build(args: argparse.Namespace) -> None:
    build(args.name)


def cmd_run(args: argparse.Namespace) -> None:
    run(args.name, args.prog, args.data)


def cmd_all(args: argparse.Namespace) -> None:
    for name in sorted(discover_tbs()):
        run(name, args.prog, args.data)


def cmd_wave(args: argparse.Namespace) -> None:
    vcd = WAVES_DIR / f"{args.name}.vcd"
    if not vcd.exists():
        fail(f"waveform not found: {rel(vcd)}\nrun it first: mycup run {args.name}")
    subprocess.run(["gtkwave", str(vcd)], cwd=ROOT)


def cmd_lint(_: argparse.Namespace) -> None:
    ensure_dirs()
    write_verilator_f()
    log_line(LINT_LOG, f"Linting: {now()}")
    proc = subprocess.run(
        ["verilator", "-f", str(VERILATOR_F)], cwd=ROOT, capture_output=True, text=True
    )
    output = proc.stdout + proc.stderr
    sys.stdout.write(output)
    with LINT_LOG.open("a", encoding="utf-8") as fh:
        fh.write(output)
    if proc.returncode != 0:
        raise SystemExit(proc.returncode)


def cmd_test(args: argparse.Namespace) -> None:
    extra = list(args.pytest_args)
    if extra and extra[0] == "--":
        extra = extra[1:]
    cmd = [sys.executable, "-m", "pytest", "-v", *extra]
    raise SystemExit(subprocess.run(cmd, cwd=ROOT).returncode)


def cmd_clean(_: argparse.Namespace) -> None:
    for d in (BUILD_DIR, WAVES_DIR, LOGS_DIR):
        shutil.rmtree(d, ignore_errors=True)
    print("Cleaned build/, waves/, logs/")


# --------------------------------------------------------------------------- #
# cli
# --------------------------------------------------------------------------- #
def make_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="mycup",
        description="my_cup 工具链（仿真 / lint / 测试）",
    )
    sub = parser.add_subparsers(dest="command", required=True)

    sub.add_parser("init", help="生成全部文件清单（filelists + verilator.f）").set_defaults(
        func=cmd_init
    )
    sub.add_parser("list", help="列出所有 testbench").set_defaults(func=cmd_list)

    p_build = sub.add_parser("build", help="编译单个 testbench")
    p_build.add_argument("name")
    p_build.set_defaults(func=cmd_build)

    p_run = sub.add_parser("run", help="编译并运行单个 testbench")
    p_run.add_argument("name")
    p_run.add_argument("--prog", help="指令存储器 hex 文件（传给 +instr=）")
    p_run.add_argument("--data", help="数据存储器 hex 文件（传给 +data=）")
    p_run.set_defaults(func=cmd_run)

    p_all = sub.add_parser("all", help="编译并运行全部 testbench")
    p_all.add_argument("--prog", help="指令存储器 hex 文件（传给 +instr=）")
    p_all.add_argument("--data", help="数据存储器 hex 文件（传给 +data=）")
    p_all.set_defaults(func=cmd_all)

    p_wave = sub.add_parser("wave", help="用 gtkwave 打开波形")
    p_wave.add_argument("name")
    p_wave.set_defaults(func=cmd_wave)

    sub.add_parser("lint", help="运行 Verilator lint").set_defaults(func=cmd_lint)

    p_test = sub.add_parser("test", help="运行 cocotb + pytest")
    p_test.add_argument("pytest_args", nargs=argparse.REMAINDER)
    p_test.set_defaults(func=cmd_test)

    sub.add_parser("clean", help="清理 build/ waves/ logs/").set_defaults(func=cmd_clean)

    return parser


def main(argv: list[str] | None = None) -> int:
    sys.stdout.reconfigure(line_buffering=True)
    sys.stderr.reconfigure(line_buffering=True)
    parser = make_parser()
    args = parser.parse_args(argv)
    args.func(args)
    return 0


if __name__ == "__main__":
    sys.exit(main())
