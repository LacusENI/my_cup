#!/bin/bash

# 生成 verilator.f —— 供 `make lint` 与 IDE (Verilog-HDL/SystemVerilog 扩展) 共用的
# Verilator 文件清单，作为工程 lint 的单一事实来源。
#
# 用法: make filelist   (或 make init)

set -e

OUT="verilator.f"
RTL_DIR="rtl"
INC_PATHS="rtl/core/include lib sim/tb/include"
FLAGS="--lint-only -Wall --timing --bbox-sys"

{
    echo "// Generated by chore/gen_lint_f.sh -- do not edit by hand"
    echo "// regenerate with: make filelist"
    echo "// Flags and include paths mirror the project lint baseline."
    # Verilator 的 -f 清单按行解析，每个 token 一行
    for t in $FLAGS; do echo "$t"; done
    for i in $INC_PATHS; do echo "-I$i"; done
    find "$RTL_DIR" -name '*.v' | sort
} > "$OUT"

echo "Generated $OUT ($(grep -c '\.v$' "$OUT") rtl files)"
