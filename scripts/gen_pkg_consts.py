#!/usr/bin/env python3
"""从 ``cpu_pkg.sv`` 生成 Python 测试常量。

为什么需要这个生成器：

- RTL 里的控制枚举（``alu_op_t`` / ``npc_op_t`` / ``wb_sel_t`` / ``src2_sel_t``）
  是测试的对外契约；
- 如果测试里再手写 ``ALU_ADD = 1``，RTL 改了枚举顺序或值，测试不会知道；
- 这里用 Verilator 的 SystemVerilog 前端导出 AST XML，再从 XML 里读取
  ``enumitem`` 的名字和值，生成 Python 常量。

输入/输出路径由 ``mycup code-gen`` 从 ``toolchain.toml`` 传入：

    uv run mycup code-gen
    uv run mycup code-gen --check

也可以直接运行：

    uv run python scripts/gen_pkg_consts.py \
        --source rtl/cpu_pkg.sv \
        --output tests/utils/cpu_pkg.py

Verilator 只负责“解析并导出 AST”，不参与编译/仿真：

    verilator --xml-only --xml-output build/cpu_pkg.xml rtl/cpu_pkg.sv
"""

from __future__ import annotations

import argparse
import difflib
import re
import shutil
import subprocess
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SOURCE = ROOT / "rtl" / "cpu_pkg.sv"
DEFAULT_OUTPUT = ROOT / "tests" / "utils" / "cpu_pkg.py"

# Verilator XML 里的字面量格式，例如 2'h1、3'b010、1'd0。
_LITERAL_RE = re.compile(
    r"^(?P<width>\d+)'[sS]?(?P<base>[bBoOdDhH])(?P<digits>[0-9a-fA-F_]+)$"
)
_BASE_MAP = {
    "b": 2,
    "o": 8,
    "d": 10,
    "h": 16,
}


def display(path: Path) -> str:
    try:
        return path.relative_to(ROOT).as_posix()
    except ValueError:
        return str(path)


def generated_header(source: Path) -> str:
    return f'''\
"""由 scripts/gen_pkg_consts.py 从 {display(source)} 生成，请勿手工修改。

这些常量对应 RTL 里的 enum，测试直接 import 即可。
修改来源后运行：make code-gen
"""

# Generated by scripts/gen_pkg_consts.py -- do not edit by hand.
'''


def parse_verilog_literal(text: str) -> int:
    """把 Verilator XML 里的 ``2'h1`` 这类字面量转换成 int。"""
    text = text.strip().replace("&apos;", "'")
    match = _LITERAL_RE.match(text)
    if not match:
        # 少数情况下 Verilator 可能直接给十进制字符串。
        return int(text, 0)

    digits = match.group("digits").replace("_", "")
    if any(ch in digits.lower() for ch in ("x", "z")):
        raise ValueError(f"枚举值不是确定的常量: {text}")
    return int(digits, _BASE_MAP[match.group("base").lower()])


def export_ast_xml(source: Path) -> ET.Element:
    """用 Verilator 导出指定 package 的 AST XML，并返回根节点。"""
    verilator = shutil.which("verilator")
    if verilator is None:
        raise SystemExit("找不到 verilator；请先安装 Verilator")

    xml_path = ROOT / "build" / f"{source.stem}.xml"
    xml_path.parent.mkdir(parents=True, exist_ok=True)
    proc = subprocess.run(
        [
            verilator,
            "--xml-only",
            "--xml-output",
            str(xml_path),
            str(source),
        ],
        cwd=ROOT,
        capture_output=True,
        text=True,
    )
    if proc.returncode != 0:
        sys.stderr.write(proc.stdout)
        sys.stderr.write(proc.stderr)
        raise SystemExit(f"verilator --xml-only 失败，退出码 {proc.returncode}")

    return ET.parse(xml_path).getroot()


def collect_enums(root: ET.Element) -> list[tuple[str, list[tuple[str, int]]]]:
    """从 XML 中收集 enumdtype -> [(enumitem 名, 值), ...]。"""
    groups: list[tuple[str, list[tuple[str, int]]]] = []

    for enum in root.iter("enumdtype"):
        type_name = enum.get("name") or "<unnamed>"
        # Verilator 输出形如 cpu_pkg::alu_op_t；生成文件里只保留类型名。
        type_name = type_name.removeprefix("cpu_pkg::")

        items: list[tuple[str, int]] = []
        for item in enum.findall("enumitem"):
            name = item.get("name")
            const = item.find("const")
            if not name or const is None or const.get("name") is None:
                raise SystemExit(f"无法解析枚举 {type_name} 的成员 {name!r}")
            items.append((name, parse_verilog_literal(const.get("name", ""))))

        if items:
            groups.append((type_name, items))

    if not groups:
        raise SystemExit("在 cpu_pkg.sv 的 AST 中没有找到 enum")

    return groups


def generate(root: ET.Element, source: Path) -> str:
    lines = [generated_header(source).rstrip(), ""]
    for type_name, items in collect_enums(root):
        lines.append(f"# {type_name}")
        for name, value in items:
            lines.append(f"{name} = {value}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument(
        "--check",
        action="store_true",
        help="只检查生成文件是否最新，不写文件",
    )
    args = parser.parse_args(argv)

    source = args.source if args.source.is_absolute() else ROOT / args.source
    output = args.output if args.output.is_absolute() else ROOT / args.output

    generated = generate(export_ast_xml(source), source)

    if args.check:
        current = output.read_text(encoding="utf-8") if output.exists() else ""
        if current == generated:
            print(f"{display(output)} 已是最新")
            return 0

        diff = difflib.unified_diff(
            current.splitlines(),
            generated.splitlines(),
            fromfile=display(output),
            tofile="generated",
            lineterm="",
        )
        print("\n".join(diff))
        return 1

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(generated, encoding="utf-8")
    print(f"Generated {display(output)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
